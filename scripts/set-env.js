// Writes src/environments/secrets.ts (git-ignored) with the API keys.
// GOOGLE_MAPS_API_KEY (e.g. set on Railway) wins; locally an existing secrets.ts is kept as is.
const fs = require('fs');
const path = require('path');

const secretsPath = path.join(__dirname, '..', 'src', 'environments', 'secrets.ts');
const apiKey = process.env.GOOGLE_MAPS_API_KEY;

if (apiKey === undefined && fs.existsSync(secretsPath)) {
  console.log('secrets.ts: kept existing file');
  process.exit(0);
}

const content = `// Generated by scripts/set-env.js - do not commit (git-ignored)
export const secrets = {
  googleMapsApiKey: '${apiKey ?? ''}',
};
`;
fs.writeFileSync(secretsPath, content);

console.log(`secrets.ts: googleMapsApiKey ${apiKey ? 'set from GOOGLE_MAPS_API_KEY' : 'left empty (GOOGLE_MAPS_API_KEY not set)'}`);
